"""Grid search for the Isolation Forest.

    python -m ml.tune                 # run the grid, write docs/tuning_results.{csv,md}

Configs are ranked by VALIDATION F1 only. Test metrics are recorded for
reference, but they never influence the choice: picking on test would leak
the test set into the model and overstate real-world performance.

This script does not save a model. Retrain the winner with ml.train,
using the command printed at the end.
"""

from __future__ import annotations

import argparse
import itertools
import time
from pathlib import Path

import pandas as pd

from ml.train import train

GRID = {
    "log_numeric": [False, True],
    "drop_duplicates": [False, True],
    "max_samples": ["auto", 2048, 8192],   # "auto" = 256 rows per tree
    "n_estimators": [100, 300],
}


def run_grid(train_df: pd.DataFrame, test_df: pd.DataFrame, grid: dict) -> pd.DataFrame:
    keys = list(grid)
    combos = list(itertools.product(*grid.values()))
    rows = []
    for i, values in enumerate(combos, 1):
        cfg = dict(zip(keys, values))
        t0 = time.perf_counter()
        _, meta = train(train_df, test_df, **cfg)
        val, test = meta["metrics"]["validation"], meta["metrics"]["test"]
        rows.append(
            {
                **cfg,
                "threshold": meta["score"]["threshold"],
                "val_f1": val["f1"],
                "val_auc": val["roc_auc"],
                "test_precision": test["precision"],
                "test_recall": test["recall"],
                "test_f1": test["f1"],
                "test_auc": test["roc_auc"],
                "seconds": round(time.perf_counter() - t0, 1),
            }
        )
        print(f"[{i}/{len(combos)}] {cfg} val_f1={val['f1']} test_f1={test['f1']}", flush=True)
    return pd.DataFrame(rows).sort_values(["val_f1", "val_auc"], ascending=False)


def to_markdown(results: pd.DataFrame) -> str:
    cols = list(results.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in results.iterrows():
        lines.append("| " + " | ".join(str(r[c]) for c in cols) + " |")
    return "\n".join(lines)


def train_command(best: pd.Series) -> str:
    # Use best["..."], not best.drop_duplicates: attribute access on a Series
    # returns the pandas *method* of that name, which is always truthy.
    cmd = (
        f"python -m ml.train --n-estimators {best['n_estimators']} "
        f"--max-samples {best['max_samples']}"
    )
    if bool(best["log_numeric"]):
        cmd += " --log-numeric"
    if bool(best["drop_duplicates"]):
        cmd += " --drop-duplicates"
    return cmd


def main(argv=None) -> None:
    p = argparse.ArgumentParser(description="Tune the Isolation Forest.")
    p.add_argument("--train", default="data/raw/UNSW_NB15_training-set.csv")
    p.add_argument("--test", default="data/raw/UNSW_NB15_testing-set.csv")
    p.add_argument("--out", default="docs/tuning_results")
    args = p.parse_args(argv)

    results = run_grid(pd.read_csv(args.train), pd.read_csv(args.test), GRID)

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    results.to_csv(out.with_suffix(".csv"), index=False)
    best = results.iloc[0]
    out.with_suffix(".md").write_text(
        "# Isolation Forest tuning results\n\n"
        "Generated by `python -m ml.tune`. Ranked by **validation F1**; "
        "test columns are for reference only and were not used to choose.\n\n"
        f"Grid: `{GRID}`\n\n"
        f"Best config: `{train_command(best)}`\n\n"
        + to_markdown(results)
        + "\n",
        encoding="utf-8",
    )
    print("\nTop 5 by validation F1:")
    print(results.head(5).to_string(index=False))
    print(f"\nRetrain the winner with:\n  {train_command(best)} --baseline")


if __name__ == "__main__":
    main()
